const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const zlib = require("node:zlib");
const esbuild = require("esbuild");
const { tikzSourceFingerprint } = require("./tikz-source-fingerprint.cjs");

const root = path.resolve(__dirname, "..");
const crateManifest = path.join(root, "crates", "chord-tikz-core", "Cargo.toml");
const wasmPath = path.join(
  root,
  "crates",
  "chord-tikz-core",
  "target",
  "wasm32-unknown-unknown",
  "release",
  "chord_tikz_core.wasm",
);
const generatedModule = path.join(
  root,
  "src",
  "tikz",
  "wasm",
  "generatedChordTikzAssets.ts",
);

void main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.stack : error}\n`);
  process.exitCode = 1;
});

async function main() {
  if (!process.argv.includes("--skip-cargo")) {
    const cargo = spawnSync(
      "cargo",
      [
        "build",
        "--release",
        "--target",
        "wasm32-unknown-unknown",
        "--manifest-path",
        crateManifest,
      ],
      { cwd: root, stdio: "inherit", windowsHide: true },
    );
    if (cargo.error) throw cargo.error;
    if (cargo.status !== 0) process.exit(cargo.status ?? 1);
  } else if (!fs.existsSync(wasmPath)) {
    throw new Error(`Built vector WASM is missing: ${wasmPath}`);
  }

  const workerBuild = await esbuild.build({
    entryPoints: [path.join(root, "src", "tikz", "wasm", "chordTikzWorker.ts")],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
    write: false,
  });
  const workerSource = workerBuild.outputFiles[0].text;
  const wasm = fs.readFileSync(wasmPath);
  const wasmGzip = gzipForEmbedding(wasm);
  const wasmSha256 = crypto.createHash("sha256").update(wasm).digest("hex");
  const moduleSource = [
    "// Generated by scripts/build-chord-tikz-wasm.cjs. Do not edit.",
    'export const CHORD_TIKZ_ENGINE_VERSION = "0.1.1";',
    `export const CHORD_TIKZ_SOURCE_SHA256 = "${tikzSourceFingerprint()}";`,
    `export const CHORD_TIKZ_WASM_SHA256 = "${wasmSha256}";`,
    `export const CHORD_TIKZ_WASM_GZIP_BASE64 = ${JSON.stringify(wasmGzip.toString("base64"))};`,
    `export const CHORD_TIKZ_WORKER_SOURCE = ${JSON.stringify(workerSource)};`,
    "",
  ].join("\n");
  fs.writeFileSync(generatedModule, moduleSource, "utf8");
  process.stdout.write(
    `Embedded Chord TikZ assets: vector-wasm=${wasm.byteLength}->${wasmGzip.byteLength}\n`,
  );
}

function gzipForEmbedding(bytes) {
  return zlib.gzipSync(bytes, {
    level: zlib.constants.Z_BEST_COMPRESSION,
  });
}
